/**
 * Converts a DE-Lab Pro Circuit to HNeemann Digital XML (.dig) string
 */
export function exportToDigitalXML(circuit: Circuit): string {
  const visualElementsXML = circuit.nodes.map(node => {
    const elemName = DELAB_TO_DIGITAL_TYPE[node.type] || 'And';
    const labelEntry = node.label ? `
      <elementAttributes>
        <entry>
          <string>Label</string>
          <string>${escapeXML(node.label)}</string>
        </entry>
      </elementAttributes>` : '<elementAttributes/>';

    return `    <visualElement>
      <elementName>${elemName}</elementName>${labelEntry}
      <pos x="${Math.round(node.x)}" y="${Math.round(node.y)}"/>
      <rotate>0</rotate>
    </visualElement>`;
  }).join('\n');

  const wiresXML = circuit.wires.map(wire => {
    const fromNode = circuit.nodes.find(n => n.id === wire.fromNodeId);
    const toNode = circuit.nodes.find(n => n.id === wire.toNodeId);
    if (!fromNode || !toNode) return '';

    const x1 = Math.round(fromNode.x + 90);
    const y1 = Math.round(fromNode.y + 24 + wire.fromPortIndex * 18);
    const x2 = Math.round(toNode.x);
    const y2 = Math.round(toNode.y + 24 + wire.toPortIndex * 18);

    return `    <wire>
      <p1 x="${x1}" y="${y1}"/>
      <p2 x="${x2}" y="${y2}"/>
    </wire>`;
  }).filter(Boolean).join('\n');

  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by DE-Lab Pro (Referenced from HNeemann Digital) -->
<circuit>
  <version>1</version>
  <attributes>
    <entry>
      <string>Description</string>
      <string>${escapeXML(circuit.name)}</string>
    </entry>
  </attributes>
  <visualElements>
${visualElementsXML}
  </visualElements>
  <wires>
${wiresXML}
  </wires>
</circuit>`;
}

/**
 * Parses HNeemann Digital (.dig) XML file into a DE-Lab Pro Circuit
 */
export function importFromDigitalXML(xmlText: string): { success: boolean; circuit?: Circuit; error?: string } {
  try {
    const parser = new DOMParser();
    const doc = parser.parseFromString(xmlText, 'text/xml');

    const parserError = doc.querySelector('parsererror');
    if (parserError) {
      return { success: false, error: 'Malformed XML format in .dig file.' };
    }

    const visualElements = doc.querySelectorAll('visualElement');
    if (visualElements.length === 0) {
      return { success: false, error: 'No visual elements found in .dig file.' };
    }

    const nodes: CircuitNode[] = [];
    const nodePinMap = new Map<string, { nodeId: string; x: number; y: number }>();

    let idx = 1;
    visualElements.forEach(elem => {
      const elemName = elem.querySelector('elementName')?.textContent?.trim() || 'And';
      const posElem = elem.querySelector('pos');
      const posX = posElem ? parseInt(posElem.getAttribute('x') || '100', 10) : 100;
      const posY = posElem ? parseInt(posElem.getAttribute('y') || '100', 10) : 100;

      // Extract label if present
      let label = elemName;
      const entries = elem.querySelectorAll('entry');
      entries.forEach(entry => {
        const key = entry.children[0]?.textContent?.trim();
        const val = entry.children[1]?.textContent?.trim();
        if (key === 'Label' && val) {
          label = val;
        }
      });

      const delabType = DIGITAL_TO_DELAB_TYPE[elemName] || 'AND';
      const nodeId = `node_${idx++}`;

      let inputs: CircuitNode['inputs'] = [];
      let outputs: CircuitNode['outputs'] = [];

      if (delabType === 'SWITCH') {
        outputs = [{ id: 'out_0', name: 'Q', type: 'output', value: 0 }];
      } else if (delabType === 'LED') {
        inputs = [{ id: 'in_0', name: 'In', type: 'input', value: 0 }];
        outputs = [{ id: 'out_0', name: 'Val', type: 'output', value: 0 }];
      } else if (delabType === 'NOT') {
        inputs = [{ id: 'in_0', name: 'A', type: 'input', value: 0 }];
        outputs = [{ id: 'out_0', name: 'Y', type: 'output', value: 1 }];
      } else if (delabType === 'D_FF') {
        inputs = [
          { id: 'in_0', name: 'D', type: 'input', value: 0 },
          { id: 'in_1', name: 'CLK', type: 'input', value: 0 },
        ];
        outputs = [
          { id: 'out_0', name: 'Q', type: 'output', value: 0 },
          { id: 'out_1', name: "Q'", type: 'output', value: 1 },
        ];
      } else if (delabType === 'JK_FF') {
        inputs = [
          { id: 'in_0', name: 'J', type: 'input', value: 0 },
          { id: 'in_1', name: 'K', type: 'input', value: 0 },
          { id: 'in_2', name: 'CLK', type: 'input', value: 0 },
        ];
        outputs = [
          { id: 'out_0', name: 'Q', type: 'output', value: 0 },
          { id: 'out_1', name: "Q'", type: 'output', value: 1 },
        ];
      } else {
        inputs = [
          { id: 'in_0', name: 'A', type: 'input', value: 0 },
          { id: 'in_1', name: 'B', type: 'input', value: 0 },
        ];
        outputs = [{ id: 'out_0', name: 'Y', type: 'output', value: 0 }];
      }

      const node: CircuitNode = {
        id: nodeId,
        type: delabType,
        label,
        x: posX,
        y: posY,
        inputs,
        outputs,
      };

      nodes.push(node);
      nodePinMap.set(`${posX},${posY}`, { nodeId, x: posX, y: posY });
    });

    // Parse Wires
    const wires: Wire[] = [];
    const wireElements = doc.querySelectorAll('wire');
    let wireIdx = 1;

    wireElements.forEach(wElem => {
      const p1 = wElem.querySelector('p1');
      const p2 = wElem.querySelector('p2');
      if (!p1 || !p2) return;

      const x1 = parseInt(p1.getAttribute('x') || '0', 10);
      const y1 = parseInt(p1.getAttribute('y') || '0', 10);
      const x2 = parseInt(p2.getAttribute('x') || '0', 10);
      const y2 = parseInt(p2.getAttribute('y') || '0', 10);

      // Find closest source node and destination node
      const fromCandidate = findClosestNode(nodes, x1, y1);
      const toCandidate = findClosestNode(nodes, x2, y2);

      if (fromCandidate && toCandidate && fromCandidate.id !== toCandidate.id) {
        wires.push({
          id: `w_dig_${wireIdx++}`,
          fromNodeId: fromCandidate.id,
          fromPortIndex: 0,
          toNodeId: toCandidate.id,
          toPortIndex: 0,
          value: 0,
        });
      }
    });

    const circuitName = doc.querySelector('attributes > entry > string:last-child')?.textContent || 'Imported Digital Circuit';

    const importedCircuit: Circuit = {
      id: `dig_import_${Date.now()}`,
      name: circuitName,
      description: 'Imported from HNeemann Digital .dig file',
      createdAt: Date.now(),
      updatedAt: Date.now(),
      nodes,
      wires,
    };

    return { success: true, circuit: importedCircuit };
  } catch (err: unknown) {
    return { success: false, error: err instanceof Error ? err.message : 'Failed parsing .dig file' };
  }
}

function findClosestNode(nodes: CircuitNode[], x: number, y: number): CircuitNode | null {
  let closest: CircuitNode | null = null;
  let minDist = 150; // tolerance threshold

  for (const n of nodes) {
    const dist = Math.hypot(n.x - x, n.y - y);
    if (dist < minDist) {
      minDist = dist;
      closest = n;
    }
  }

  return closest;
}

function escapeXML(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}
